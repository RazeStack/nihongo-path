import type { ExampleWord, GrammarPoint } from '@/types/content'

function forms(
  presentAffirmative: [string, string, string],
  presentNegative: [string, string, string],
  pastAffirmative: [string, string, string],
  pastNegative: [string, string, string],
): ExampleWord[] {
  return [presentAffirmative, presentNegative, pastAffirmative, pastNegative].map(([japanese, romaji, translation]) => ({
    japanese,
    romaji,
    translation,
  }))
}

